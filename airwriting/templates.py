"""Hand-designed stroke templates for digits 0-9 and capital letters A-Z.

Each character has a few common ways people write it in the air (stroke
order, open/closed 4, 7 with or without a bar, ...). Coordinates are in glyph
units: x to the right, y downwards, the character is 1.0 tall.

Templates are only the starting point: train_model.py distorts them heavily
(slant, wobble, jitter, uneven strokes, joined strokes...) to imitate real
fingertip trajectories.
"""

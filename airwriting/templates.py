# --- small drawing helpers ---------------------------------------------------

def L(*pts):
    """Straight polyline through the given points."""
    return np.array(pts, dtype=np.float32)


def A(cx, cy, rx, ry, a0, a1, step=6.0):
    """Elliptical arc. Angles in degrees, 0 = right, 90 = down (screen coordinates)."""
    n = max(6, int(abs(a1 - a0) / step) + 1)
    t = np.radians(np.linspace(a0, a1, n))
    return np.stack([cx + rx * np.cos(t), cy + ry * np.sin(t)], axis=1).astype(np.float32)


def S(*pts, n=10):
    """Smooth Catmull-Rom curve passing through the given points."""
    P = np.array(pts, dtype=np.float64)
    P = np.vstack([P[0], P, P[-1]])
    out = []
    t = np.linspace(0.0, 1.0, n, endpoint=False)[:, None]
    t2, t3 = t * t, t * t * t
    for i in range(1, len(P) - 2):
        p0, p1, p2, p3 = P[i - 1], P[i], P[i + 1], P[i + 2]
        out.append(0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2
                          + (-p0 + 3 * p1 - 3 * p2 + p3) * t3))
    out.append(P[-2][None])
    return np.vstack(out).astype(np.float32)


def C(*parts):
    """Join several pieces into one continuous stroke."""
    return np.vstack(parts).astype(np.float32)


